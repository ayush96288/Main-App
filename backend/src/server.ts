import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import {z} from "zod";
import {auth,role} from "./middleware.js";
import {issueAccessToken,issueRefreshToken,hashToken,otp,requestId} from "./security.js";
const app=express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({origin:process.env.WEB_ORIGIN?.split(",")||false,credentials:true}));
app.use(express.json({limit:"5mb"}));
app.use((req,res,next)=>{res.setHeader("x-request-id",requestId());next()});
app.use(rateLimit({windowMs:60_000,max:120,standardHeaders:true,legacyHeaders:false}));
app.get("/health",(_,res)=>res.json({ok:true,service:"scribelink-api"}));
app.post("/auth/request-otp",rateLimit({windowMs:10*60_000,max:5}),(_,res)=>res.json({accepted:true,expiresIn:300,developmentOtp:process.env.NODE_ENV==="development"?otp():undefined}));
app.post("/auth/refresh",(req,res)=>{const token=z.string().min(32).safeParse(req.body?.refreshToken);if(!token.success)return res.status(401).json({error:"invalid_refresh"});res.json({accessToken:issueAccessToken("demo-user","CUSTOMER")});});
app.get("/me",auth,(req,res)=>res.json({user:(req as any).user}));
app.post("/orders",(req,res)=>{const body=z.object({pages:z.number().int().positive().max(500),scribeId:z.string().optional()}).safeParse(req.body);if(!body.success)return res.status(400).json({error:"invalid_request"});res.status(201).json({id:"SL-NEW",pages:body.data.pages,price:body.data.pages*30,status:"PAID_PENDING_ACCEPTANCE"});});
app.post("/admin/audit-test",auth,role("ADMIN"),(_,res)=>res.json({ok:true}));
app.listen(Number(process.env.PORT||4000),()=>console.log("ScribeLink API listening"));